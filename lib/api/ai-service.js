import { GoogleGenerativeAI } from "@google/generative-ai";
import { appConfig } from "./config.js";

const MAX_RETRIES = 3;
const RETRY_DELAY = 1000;
const GEMINI_MODEL = "gemini-2.0-flash";

/**
 * AI Orchestrator for all AI tasks.
 * Implements Gemini integration with strict JSON enforcement and retries.
 */
async function callGemini(prompt, responseMimeType = "application/json", attempt = 1) {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey || apiKey === "your_gemini_api_key_here") {
    throw new Error("GEMINI_API_KEY is not configured");
  }

  try {
    const genAI = new GoogleGenerativeAI(apiKey);
    const model = genAI.getGenerativeModel({ 
      model: GEMINI_MODEL,
      generationConfig: { responseMimeType }
    });

    const result = await model.generateContent(prompt);
    const response = await result.response;
    const text = response.text();
    
    if (responseMimeType === "application/json") {
      return JSON.parse(text);
    }
    return text;
  } catch (error) {
    if (attempt < MAX_RETRIES) {
      await new Promise(resolve => setTimeout(resolve, RETRY_DELAY * attempt));
      return callGemini(prompt, responseMimeType, attempt + 1);
    }
    throw error;
  }
}

export async function evaluateWithAi({ text, rubric, style = "Standard" }) {
  const criteria = rubric?.criteria || [];
  
  const prompt = `
    You are an expert academic reviewer. Evaluate the following document text against the provided rubric criteria and style.
    
    Document Text:
    ${text}
    
    Rubric Criteria:
    ${JSON.stringify(criteria, null, 2)}
    
    Style: ${style}
    
    Return a JSON object matching this exact schema:
    {
      "status": "completed",
      "summary": "Short overall summary of the feedback",
      "scores": [
        {
          "criterion": "Name of criterion",
          "score": number,
          "maxScore": number,
          "explanation": "Brief explanation for the score"
        }
      ],
      "recommendations": ["string", "string", "string"],
      "checklist": [
        { "item": "string", "completed": boolean }
      ],
      "suggestions": [
        {
          "type": "grammar" | "clarity" | "logic",
          "severity": "low" | "medium" | "high",
          "location": { "paragraph": number },
          "original": "original text snippet",
          "suggestion": "suggested improvement",
          "reason": "reason for the suggestion"
        }
      ],
      "formattingViolations": [
        {
          "style": "${style}",
          "severity": "low" | "medium" | "high",
          "location": "e.g. Title, Bibliography",
          "message": "description of the violation"
        }
      ],
      "disclaimer": "Standard AI feedback disclaimer"
    }
    
    Ensure "overallScore" is NOT included in the JSON as it will be calculated from the scores array.
    Focus on being constructive and specific.
  `;

  try {
    return await callGemini(prompt);
  } catch (error) {
    console.error("Gemini evaluation failed, falling back to grounded analysis:", error.message);
    return runGroundedEvaluation({ text, criteria, style });
  }
}

